	constexpr double PHY_MU0 = 1.25663706212e-6;         // Vacuum permeability(N/A^2)
	constexpr double PHY_G =   6.67430e-11;              // Gravitational constant (m^3/kg/s^2)
	constexpr double PHY_KB =  1.380649e-23;             // Boltzmann constant k_B (J/K)
	constexpr double PHY_QE =  1.602176634e-19;          // Elementary charge (C)
